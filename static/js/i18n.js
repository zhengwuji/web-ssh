const I18N_SUPPORTED_LANGUAGES = Object.freeze(["vi", "de", "fr", "es", "zh"]);
const i18nPendingBundles = new Map();
const BrowserPreferences = {
    get(key, fallback = null) {
        try {
            const value = window.localStorage?.getItem(key);
            return typeof value === 'string' && value ? value : fallback;
        } catch {
            return fallback;
        }
    },

    set(key, value) {
        try {
            window.localStorage?.setItem(key, String(value));
            return true;
        } catch {
            return false;
        }
    }
};

const storedLanguage = BrowserPreferences.get('language', 'en');

function i18nBundleUrl(lang) {
    const root = document.querySelector('meta[name="app-root"]')?.content || '';
    return `${root}/static/js/i18n/${encodeURIComponent(lang)}.json`;
}

function fetchI18nBundle(lang) {
    // Returns a Promise that registers the bundle; safe to call repeatedly.
    if (translations[lang] || !I18N_SUPPORTED_LANGUAGES.includes(lang)) {
        return Promise.resolve(lang);
    }
    let pending = i18nPendingBundles.get(lang);
    if (pending) return pending;
    pending = new Promise(resolve => {
        if (typeof fetch !== 'function') {
            resolve(lang);
            return;
        }
        fetch(i18nBundleUrl(lang), { credentials: 'same-origin' })
            .then(response => (response.ok ? response.json() : Promise.reject(response.status)))
            .then(table => {
                if (table && typeof table === 'object' && !translations[lang]) {
                    translations[lang] = table;
                }
                resolve(lang);
            })
            .catch(() => resolve(lang));
    });
    i18nPendingBundles.set(lang, pending);
    return pending;
}

const initialLanguage = (
    translations[storedLanguage]
    || I18N_SUPPORTED_LANGUAGES.includes(storedLanguage)
) ? storedLanguage : 'en';

const i18n = {
    currentLang: initialLanguage,

    t(key) {
        const activeTranslations = translations[this.currentLang] || translations.en;
        return activeTranslations[key] || translations.en[key] || key;
    },

    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            BrowserPreferences.set('language', lang);
            this.updatePageText();

            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
            return true;
        }
        if (I18N_SUPPORTED_LANGUAGES.includes(lang)) {
            // Accept now; the bundle arrives asynchronously and re-applies.
            this.currentLang = lang;
            BrowserPreferences.set('language', lang);
            fetchI18nBundle(lang).then(() => {
                this.updatePageText();
                window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
            });
            return true;
        }
        return false;
    },

    ensureLanguage(lang) {
        return fetchI18nBundle(lang).then(loadedLang => {
            if (loadedLang === this.currentLang) {
                this.updatePageText();
            }
            return loadedLang;
        });
    },

    getLanguage() {
        return this.currentLang;
    },

    getLanguages() {
        return [
            { code: 'en', name: 'English', flag: 'EN' },
            { code: 'vi', name: 'Tiếng Việt', flag: 'VI' },
            { code: 'de', name: 'Deutsch', flag: 'DE' },
            { code: 'fr', name: 'Français', flag: 'FR' },
            { code: 'es', name: 'Español', flag: 'ES' },
            { code: 'zh', name: '中文', flag: 'ZH' }
        ];
    },

    updatePageText() {
        document.documentElement.lang = this.currentLang;

        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.t(key);

            if (element.tagName === 'INPUT' && element.type !== 'submit') {
                element.placeholder = translation;
            } else {
                element.textContent = translation;
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            element.placeholder = this.t(key);
        });

        document.querySelectorAll('[data-i18n-title]').forEach(element => {
            const key = element.getAttribute('data-i18n-title');
            element.title = this.t(key);
        });

        document.querySelectorAll('[data-i18n-label]').forEach(element => {
            const key = element.getAttribute('data-i18n-label');
            element.label = this.t(key);
        });

        document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
            const key = element.getAttribute('data-i18n-aria-label');
            element.setAttribute('aria-label', this.t(key));
        });

        document.querySelectorAll('[data-i18n-alt]').forEach(element => {
            const key = element.getAttribute('data-i18n-alt');
            element.alt = this.t(key);
        });

        if (!document.querySelector('title[data-i18n]') && document.title.includes('SSH Terminal')) {
            document.title = this.t('app.title');
        }
    }
};

window.BrowserPreferences = BrowserPreferences;
window.i18n = i18n;

document.addEventListener('DOMContentLoaded', () => {
    i18n.updatePageText();
    if (!translations[i18n.currentLang]) {
        i18n.ensureLanguage(i18n.currentLang);
    }
});
